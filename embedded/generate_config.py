"""
Generate wifi_config.py from .env for flashing to the ESP32.

Usage:
    uv run python generate_config.py

Reads .env in the same directory and writes wifi_config.py with WiFi credentials.
"""
import pathlib

HERE = pathlib.Path(__file__).parent
ENV_FILE = HERE / ".env"
WIFI_CONFIG_FILE = HERE / "wifi_config.py"

WIFI_KEYS = {"WIFI_SSID", "WIFI_PASSWORD"}

if not ENV_FILE.exists():
    raise SystemExit(
        ".env not found. Copy .env.example to .env and fill in your WiFi credentials."
    )

pairs: list[tuple[str, str]] = []
for line in ENV_FILE.read_text().splitlines():
    line = line.strip()
    if not line or line.startswith("#"):
        continue
    if "=" not in line:
        continue
    key, _, value = line.partition("=")
    key = key.strip()
    if key in WIFI_KEYS:
        pairs.append((key, value.strip()))

missing = WIFI_KEYS - {key for key, _ in pairs}
if missing:
    raise SystemExit(f"Missing keys in .env: {', '.join(sorted(missing))}")

lines = ["# Generated by generate_config.py — do not edit by hand\n"]
for key, value in pairs:
    lines.append(f"{key} = '{value}'\n")

WIFI_CONFIG_FILE.write_text("".join(lines))

print("Written wifi_config.py:")
for key, value in pairs:
    display = "***" if "PASSWORD" in key else value
    print(f"  {key} = {display}")
