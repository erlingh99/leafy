"""
Generate config.py from .env for flashing to the ESP32.

Usage:
    python generate_config.py

Reads .env in the same directory and writes config.py.
"""
import os
import pathlib

HERE = pathlib.Path(__file__).parent
ENV_FILE = HERE / ".env"
CONFIG_FILE = HERE / "config.py"

INTEGER_KEYS = {"ADC_PIN", "ADC_DRY", "ADC_WET", "READING_INTERVAL_SECONDS", "MAX_RETRIES", "RETRY_DELAY_SECONDS"}

if not ENV_FILE.exists():
    raise SystemExit(f".env not found. Copy .env.example to .env and fill in your values.")

pairs: list[tuple[str, str]] = []
for line in ENV_FILE.read_text().splitlines():
    line = line.strip()
    if not line or line.startswith("#"):
        continue
    if "=" not in line:
        continue
    key, _, value = line.partition("=")
    pairs.append((key.strip(), value.strip()))

lines = ["# Generated by generate_config.py — do not edit by hand\n"]
for key, value in pairs:
    if key in INTEGER_KEYS:
        lines.append(f"{key} = {int(value)}\n")
    else:
        lines.append(f"{key} = '{value}'\n")

CONFIG_FILE.write_text("".join(lines))

print("Written config.py:")
for key, value in pairs:
    display = "***" if "PASSWORD" in key else value
    print(f"  {key} = {display}")
